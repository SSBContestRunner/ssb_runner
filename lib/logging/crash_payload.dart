import 'package:package_info_plus/package_info_plus.dart';
import 'package:catcher_2/model/report.dart';
import 'package:ssb_runner/logging/log_export.dart';
import 'package:ssb_runner/logging/log_session.dart';
import 'package:ssb_runner/logging/redaction.dart';

const int _maxIssueTitleLength = 240;
const int _maxIssueBodyLength = 60000;
const int _logTailLines = 150;

/// Device parameters that identify a specific machine and must not be
/// published in a public issue or written into the shared log file.
const Set<String> _privateDeviceKeys = <String>{
  'computerName',
  'hostName',
  'machineId',
  'androidId',
  'serialNumber',
};

/// Returns the device parameters that are safe to publish.
Map<String, dynamic> safeDeviceParameters(Map<String, dynamic> parameters) {
  return <String, dynamic>{
    for (final entry in parameters.entries)
      if (!_privateDeviceKeys.contains(entry.key)) entry.key: entry.value,
  };
}

/// Title/body pair sent to GitHub, plus the short comment used when the crash
/// matches an issue that is already open.
class CrashIssuePayload {
  const CrashIssuePayload({
    required this.title,
    required this.body,
    required this.duplicateComment,
  });

  final String title;
  final String body;
  final String duplicateComment;
}

/// Builds the issue payload from the report and the diagnostics already
/// persisted by the logging pipeline.
Future<CrashIssuePayload> buildCrashIssuePayload(Report report) async {
  final info = await _tryPackageInfo();
  final version = info == null
      ? 'unknown'
      : '${info.version}+${info.buildNumber}';
  final errorType =
      report.error?.runtimeType.toString() ??
      report.errorDetails?.exception.runtimeType.toString() ??
      'unknown';
  final platform = report.platformType.name;
  final caughtAt = report.dateTime.toUtc().toIso8601String();

  final title = _clip(
    '[crash] $errorType · $version · $platform · ${_topFrame(report.stackTrace)}',
    _maxIssueTitleLength,
    suffix: '...',
  );

  final header = LogSession.headerLines.isEmpty
      ? 'unavailable'
      : LogSession.headerLines.join('\n');
  final errorText = report.error?.toString() ?? 'unknown error';
  final detailsText = report.errorDetails?.toString().trim();
  final stackText = report.stackTrace?.toString() ?? 'unavailable';
  final logTail = redactText(
    await diagnosticSummary(tailLines: _logTailLines, currentSessionOnly: true),
  );

  final body = StringBuffer()
    ..writeln('<!-- generated by the SSB Runner crash reporter -->')
    ..writeln()
    ..writeln('**Platform:** `$platform`')
    ..writeln('**Version:** `$version`')
    ..writeln('**Error type:** `$errorType`')
    ..writeln('**Caught (UTC):** `$caughtAt`')
    ..writeln()
    ..writeln('## Environment')
    ..writeln('```text')
    ..writeln(header)
    ..writeln('```');

  _writeMapSection(
    body,
    'Device',
    safeDeviceParameters(report.deviceParameters),
  );
  _writeMapSection(body, 'Application', report.applicationParameters);

  body
    ..writeln()
    ..writeln('## Error')
    ..writeln('```text')
    ..writeln(errorText)
    ..writeln('```');

  if (detailsText != null &&
      detailsText.isNotEmpty &&
      detailsText != errorText) {
    body
      ..writeln()
      ..writeln('## Flutter error details')
      ..writeln('```text')
      ..writeln(detailsText)
      ..writeln('```');
  }

  body
    ..writeln()
    ..writeln('## Stack trace')
    ..writeln('```text')
    ..writeln(stackText)
    ..writeln('```')
    ..writeln()
    ..writeln('## Log tail')
    ..writeln('```text')
    ..writeln(logTail)
    ..writeln('```');

  return CrashIssuePayload(
    title: title,
    body: _clip(
      body.toString(),
      _maxIssueBodyLength,
      suffix: '\n\n... (truncated)',
    ),
    duplicateComment:
        'Also happened on `$platform` / `$version` at `$caughtAt`.',
  );
}

/// Request body accepted by the Cloudflare Worker crash proxy.
///
/// Only the fields in this map are sent; the browser never sees a GitHub token.
Future<Map<String, Object?>> buildWebCrashPayload(Report report) async {
  final info = await _tryPackageInfo();
  final errorType =
      report.error?.runtimeType.toString() ??
      report.errorDetails?.exception.runtimeType.toString() ??
      'unknown';
  final errorMessage =
      report.error?.toString() ?? report.errorDetails?.toString() ?? '';
  final stack = _clip(
    report.stackTrace?.toString() ?? '',
    32 * 1024,
    suffix: '\n... (truncated)',
  );
  final logs = _clip(
    redactText(
      await diagnosticSummary(
        tailLines: _logTailLines,
        currentSessionOnly: true,
      ),
    ),
    64 * 1024,
    suffix: '\n... (truncated)',
  );

  return <String, Object?>{
    'version': info?.version ?? 'unknown',
    'build': info?.buildNumber ?? '',
    'platform': report.platformType.name,
    'language': report.applicationParameters['locale'],
    'caughtAt': report.dateTime.toUtc().toIso8601String(),
    'errorType': errorType,
    'message': _clip(errorMessage, 4 * 1024, suffix: '...'),
    'stack': stack,
    'log': logs,
    'fingerprint': fingerprintFor(
      errorType: errorType,
      stack: stack,
      version: '${info?.version ?? 'unknown'}+${info?.buildNumber ?? ''}',
    ),
    'description': '',
    'contact': '',
  };
}

/// Stable identifier used by the proxy to collapse repeats of one crash.
String fingerprintFor({
  required String errorType,
  required String stack,
  required String version,
}) {
  final seed = '$errorType\n${_firstFrames(stack)}\n$version';
  var hash = 0x811c9dc5;
  for (final unit in seed.codeUnits) {
    hash ^= unit;
    hash = (hash * 0x01000193) & 0xffffffff;
  }
  return hash.toRadixString(16).padLeft(8, '0');
}

/// The first three frames carry the crash site without build-specific paths.
String _firstFrames(String stack) {
  final frames = <String>[];
  for (final line in stack.split('\n')) {
    final trimmed = line.trim();
    if (!trimmed.startsWith('#')) {
      continue;
    }
    frames.add(trimmed);
    if (frames.length == 3) {
      break;
    }
  }
  return frames.join('\n');
}

/// Appends a fenced key/value block when [values] is not empty.
void _writeMapSection(
  StringBuffer buffer,
  String title,
  Map<String, dynamic> values,
) {
  if (values.isEmpty) {
    return;
  }

  final entries = values.entries.toList()
    ..sort((a, b) => a.key.compareTo(b.key));
  buffer
    ..writeln()
    ..writeln('## $title')
    ..writeln('```text');
  for (final entry in entries) {
    buffer.writeln('${entry.key}=${entry.value}');
  }
  buffer.writeln('```');
}

Future<PackageInfo?> _tryPackageInfo() async {
  try {
    return await PackageInfo.fromPlatform();
  } on Exception {
    return null;
  }
}

/// Extracts the calling symbol from the first stack frame. Line numbers and
/// file paths are left out so issues group by function rather than by build.
String _topFrame(Object? stackTrace) {
  final text = stackTrace?.toString() ?? '';
  for (final line in text.split('\n')) {
    final trimmed = line.trim();
    if (!trimmed.startsWith('#')) {
      continue;
    }

    var frame = trimmed.replaceFirst(RegExp(r'^#\d+\s+'), '');
    final paren = frame.indexOf(' (');
    if (paren > 0) {
      frame = frame.substring(0, paren);
    }
    return _clip(frame, 60, suffix: '...');
  }

  return 'unknown';
}

String _clip(String value, int maxLength, {String suffix = ''}) {
  if (value.length <= maxLength) {
    return value;
  }

  final keep = maxLength - suffix.length;
  return '${value.substring(0, keep < 0 ? 0 : keep)}$suffix';
}
